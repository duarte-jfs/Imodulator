from scipy.interpolate import CubicSpline
import numpy as np

def extend_array(
        x,y, N=100
):

    f_interp = lambda t: CubicSpline(x,y.real, axis = 1)(t)  + 1j*CubicSpline(x,y.imag, axis =1)(t)
    
    x_new = np.linspace(np.min(x), np.max(x), N)
    y_new = f_interp(x_new)

    return y_new

def get_V(
        zmin = 0,
        zmax = 10e-3,
        z0=50,
        zL=50,
        zG=50,
        gamma = 1 + 1j*0,
        length=1
):
    Gamma_L = (z0-zL)/(z0+zL)
    Gamma_G = (z0-zG)/(z0+zG)
    z = np.linspace(zmin, zmax, 100)

    V_p = 1/(1-Gamma_L*Gamma_G*np.exp(-2*gamma*length))*z0/(z0+zG)*np.exp(-gamma*z)

    V_m = Gamma_L*np.exp(-2*gamma*length)/(1-Gamma_L*Gamma_G*np.exp(-2*gamma*length))*z0/(z0+zG)*np.exp(gamma*z)

    V=V_p + V_m
    return z,V,V_p,V_m

def get_EO(
    freq,
    neff,
    loss,
    Z,
    L,
    ZS = 50,
    ZL = 50,
    N_new_freq = 100  ,
    no = 3.25
):
    
    loss_new = extend_array(freq, loss, N_new_freq)
    neff_new = extend_array(freq, neff, N_new_freq)
    Z_new = extend_array(freq, Z, N_new_freq)
    freq_new =  np.linspace(np.min(freq), np.max(freq), N_new_freq)
    
    alpha = loss_new*100 * np.log(10) / 20  # convert to Np/m
    beta = 2 * np.pi * freq_new * 1e9 * neff_new / 3e8  # in rad/m
    k = alpha + 1j * beta

    R_L = np.real(ZL)
    R_S = np.real(ZS)

    c_0 = 3e8  # speed of light in vacuum
    R_L = R_L
    R_G = R_S
    Z_0 = Z_new
    Z_L = ZL
    Z_G = ZS

    Z_in = Z_0 * (Z_L + Z_0 * np.tanh(k*L)) / (Z_0 + Z_L * np.tanh(k*L)) #RF line input impedance 
    w= freq_new*2*np.pi*1e9
    u_p = (alpha*L) + (1j* w)*(neff_new-no)*L /(c_0)
    u_m = -(alpha*L) + (1j* w)*(-neff_new-no)*L /(c_0)
    fu_p = (1 - np.exp(u_p)) / u_p
    fu_m = (1 - np.exp(u_m)) / u_m
    mw = (
        ((R_L + R_G) / R_L)
        * np.absolute(Z_in / (Z_in + Z_G))
        * np.absolute(
            (((Z_L + Z_0) * fu_p) + ((Z_L - Z_0) * fu_m))
            / (
                ((Z_L + Z_0) * np.exp(k * L))
                + ((Z_L - Z_0) * np.exp(-k * L))
            )
        )
    )
    return 20*np.log10(mw) #The factor of 20log10 is because we want to consider the EO bandwidth as the power of an electrical signal generated by the optical power, like the current of a perfect photodiode.

def get_fom_new_L(
    freq,
    neff,
    loss,
    Z,
    L,
    ZS = 50,
    ZL = 50,
    no = 3.25,
    N_new_freq = 100
):
    """
    freq: in GHz
    loss: in dB/cm
    zc: in ohm
    """
    loss_new = extend_array(freq, loss, N_new_freq)
    neff_new = extend_array(freq, neff, N_new_freq)
    Z_new = extend_array(freq, Z, N_new_freq)
    freq_new =  np.linspace(np.min(freq), np.max(freq), N_new_freq)
    
    alpha = loss_new*100 * np.log(10) / 20  # convert to Np/m
    beta = 2 * np.pi * freq_new * 1e9 * neff_new / 3e8  # in rad/m
    k = alpha + 1j * beta

    A = np.cosh(k * L)
    B = Z_new * np.sinh(k * L)
    C = np.sinh(k * L) / Z_new
    D = np.cosh(k * L)

    S11 = (A * ZL + B - C * ZL * ZS - D * ZS) / (A * ZL + B + C * ZL * ZS + D * ZS)
    S12 = (2 * np.sqrt(ZS * ZL)) / (A * ZL + B + C * ZL * ZS + D * ZS)

    EO = get_EO(
        freq,
        neff,
        loss,
        Z,
        L,
        ZS,
        ZL,
        N_new_freq,
        no
    )

    return S11, S12, EO, freq_new, loss_new, neff_new, Z_new